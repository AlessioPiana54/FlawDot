// Writes src/glyphs.generated.ts: the outlines of the digits and of the letters of the legend, taken from
// Atkinson Hyperlegible Bold (SIL Open Font License 1.1, see assets/OFL.txt), so that the marks never need a font.
//
// Usage (run by hand, from the repository root; the output is tracked):
//   node packages/annotation/scripts/extract-glyphs.mjs <font.woff> <folder that has node_modules/opentype.js>
// The font is `files/atkinson-hyperlegible-latin-700-normal.woff` of the npm package `@fontsource/atkinson-hyperlegible`
// 5.3.0, and opentype.js is 2.0.0 (installed in a scratch folder, not in this repository).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";

const EXPECTED_SHA256 = "577513bf8ebccb89f1852481d87eecbf2e10f703fbdad5ff341dd6d12d4972bd";
const EXPECTED_UNITS_PER_EM = 1000;
const OUTPUT = new URL("../src/glyphs.generated.ts", import.meta.url);

const [fontPath, toolFolder] = process.argv.slice(2);
if (fontPath === undefined || toolFolder === undefined) {
  console.error("usage: extract-glyphs.mjs <font.woff> <folder with node_modules/opentype.js>");
  process.exit(2);
}

const bytes = readFileSync(fontPath);
const sha256 = createHash("sha256").update(bytes).digest("hex");
if (sha256 !== EXPECTED_SHA256) {
  console.error(`the font file is not the one this script was written for (sha256 ${sha256})`);
  process.exit(1);
}

const opentype = createRequire(join(toolFolder, "noop.js"))("opentype.js");
const font = opentype.parse(
  bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
);
if (font.unitsPerEm !== EXPECTED_UNITS_PER_EM) {
  console.error(`unitsPerEm is ${font.unitsPerEm}, expected ${EXPECTED_UNITS_PER_EM}`);
  process.exit(1);
}

const DIGITS = "0123456789";
const LEGEND = "Critical Medium Low";
const characters = Array.from(new Set((DIGITS + LEGEND).split(""))).sort();

const glyphs = {};
for (const character of characters) {
  const glyph = font.charToGlyph(character);
  if (glyph.index === 0) {
    console.error(`the font has no glyph for ${JSON.stringify(character)}`);
    process.exit(1);
  }
  // Size 1000 on a 1000-unit em: y points down and the baseline is 0, so the top of a digit is negative.
  glyphs[character] = {
    d: character === " " ? "" : glyph.getPath(0, 0, 1000).toPathData(1),
    advance: Math.round(glyph.advanceWidth),
  };
}

// The digits of this font are not tabular, but a number in a circle is easier to read when each digit sits in a cell of
// the same width: the layout centers every digit in `DIGIT_CELL`.
const digitHeight = Math.max(
  ...DIGITS.split("").map(
    (digit) => font.charToGlyph(digit).getBoundingBox().y2 * (1000 / font.unitsPerEm),
  ),
);
const digitCell = Math.max(...DIGITS.split("").map((digit) => glyphs[digit].advance));

const lines = [
  "// GENERATED by scripts/extract-glyphs.mjs. Do not edit by hand.",
  "// Outlines derived from Atkinson Hyperlegible Bold, Copyright 2020 Braille Institute of America, Inc.,",
  "// licensed under the SIL Open Font License 1.1 (the text is in assets/OFL.txt).",
  `// Source: @fontsource/atkinson-hyperlegible 5.3.0, files/atkinson-hyperlegible-latin-700-normal.woff, sha256 ${sha256}.`,
  "",
  "export interface Glyph {",
  "  /** SVG path data, in a 1000-unit em, y pointing down, the baseline at y = 0. Empty for the space. */",
  "  readonly d: string;",
  "  /** How far the pen moves after the glyph, in the same units. */",
  "  readonly advance: number;",
  "}",
  "",
  "export const GLYPH_UNITS = 1000;",
  `export const DIGIT_HEIGHT = ${Math.round(digitHeight)};`,
  `export const DIGIT_CELL = ${digitCell};`,
  "",
  "export const GLYPHS: Readonly<Record<string, Glyph>> = {",
  ...characters.map(
    (character) => `  ${JSON.stringify(character)}: ${JSON.stringify(glyphs[character])},`,
  ),
  "};",
  "",
];
writeFileSync(OUTPUT, lines.join("\n"));
console.log(
  `wrote ${characters.length} glyphs, digit height ${Math.round(digitHeight)}, cell ${digitCell}`,
);
